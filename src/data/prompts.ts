type PromptSeed = Omit<Prompt, 'sections'> & { sectionContent: Array<[string, string]> };

const makePrompt = ({ sectionContent, ...prompt }: PromptSeed): Prompt => ({ ...prompt, sections: sections(sectionContent) });

